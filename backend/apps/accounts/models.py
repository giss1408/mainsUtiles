import uuid

from django.conf import settings
from django.contrib.auth.models import AbstractBaseUser, BaseUserManager, PermissionsMixin
from django.db import models
from django.db.models import Q


class Role(models.TextChoices):
    HOUSEHOLDER = "householder", "Particulier"
    JOBBER = "jobber", "Mini-jobber"
    STAFF = "staff", "Personnel"


class UserManager(BaseUserManager):
    def create_user(self, username=None, password=None, **extra):
        user = self.model(username=username, **extra)
        if password:
            user.set_password(password)
        else:
            user.set_unusable_password()
        user.save(using=self._db)
        return user

    def create_superuser(self, username, password=None, **extra):
        extra.setdefault("role", Role.STAFF)
        extra.setdefault("is_staff", True)
        extra.setdefault("is_superuser", True)
        return self.create_user(username=username, password=password, **extra)


class User(AbstractBaseUser, PermissionsMixin):
    """An app user (identified by phone and role) or a staff member (identified by username)."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    phone = models.CharField(max_length=20, blank=True, default="")
    role = models.CharField(max_length=20, choices=Role.choices)
    username = models.CharField(max_length=150, unique=True, null=True, blank=True)
    is_staff = models.BooleanField(default=False)
    is_active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)

    objects = UserManager()

    USERNAME_FIELD = "username"
    REQUIRED_FIELDS = []

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["phone", "role"],
                condition=~Q(role="staff"),
                name="unique_phone_per_role",
            ),
        ]

    def save(self, *args, **kwargs):
        if not self.has_usable_password() and not self.password:
            self.set_unusable_password()
        super().save(*args, **kwargs)

    def __str__(self):
        return self.username or f"{self.phone} ({self.role})"


class Device(models.Model):
    """A phone bound to one account. The id is generated by the app."""

    class Status(models.TextChoices):
        PENDING = "pending", "En attente d'activation"
        ACTIVE = "active", "Actif"
        REVOKED = "revoked", "Révoqué"

    id = models.UUIDField(primary_key=True, editable=False)
    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="devices")
    public_key = models.TextField()
    model = models.CharField(max_length=120, blank=True)
    platform = models.CharField(max_length=10, choices=[("android", "Android"), ("ios", "iOS")])
    status = models.CharField(max_length=10, choices=Status.choices, default=Status.ACTIVE)
    enrolled_at = models.DateTimeField(auto_now_add=True)
    revoked_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["user"], condition=Q(status="active"), name="one_active_device_per_user"
            ),
        ]

    def __str__(self):
        return f"{self.model or 'appareil'} ({self.status})"


class DeviceEnrolmentRequest(models.Model):
    """An application to bind a device to an account, reviewed by staff."""

    class Status(models.TextChoices):
        PENDING = "pending", "En attente"
        HELD = "held", "En vérification"
        APPROVED = "approved", "Approuvée, à envoyer"
        CODE_SENT = "code_sent", "Numéro envoyé"
        COMPLETED = "completed", "Terminée"
        REFUSED = "refused", "Refusée"
        EXPIRED = "expired", "Expirée"
        LOCKED = "locked", "Bloquée"

    class Kind(models.TextChoices):
        NEW_ACCOUNT = "new_account", "Nouveau compte"
        NEW_DEVICE = "new_device", "Nouvel appareil"

    OPEN_STATUSES = (Status.PENDING, Status.HELD, Status.APPROVED, Status.CODE_SENT)

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    phone = models.CharField(max_length=20)
    role = models.CharField(max_length=20, choices=[c for c in Role.choices if c[0] != "staff"])
    kind = models.CharField(max_length=20, choices=Kind.choices)
    device_id = models.UUIDField()
    device_model = models.CharField(max_length=120, blank=True)
    platform = models.CharField(max_length=10)
    public_key = models.TextField()
    integrity_verdict = models.CharField(max_length=20, default="unchecked")
    approx_lat = models.DecimalField(max_digits=5, decimal_places=2, null=True, blank=True)
    approx_lng = models.DecimalField(max_digits=5, decimal_places=2, null=True, blank=True)
    ip_address = models.GenericIPAddressField(null=True, blank=True)
    flags = models.JSONField(default=list, blank=True)
    status = models.CharField(max_length=20, choices=Status.choices, default=Status.PENDING)
    reason = models.TextField(blank=True)
    client_token_hash = models.CharField(max_length=64)
    code_hash = models.CharField(max_length=64, blank=True)
    previous_code_hash = models.CharField(max_length=64, blank=True)
    code_expires_at = models.DateTimeField(null=True, blank=True)
    code_attempts = models.PositiveSmallIntegerField(default=0)
    approved_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.PROTECT, related_name="+"
    )
    approved_at = models.DateTimeField(null=True, blank=True)
    sent_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.PROTECT, related_name="+"
    )
    sent_at = models.DateTimeField(null=True, blank=True)
    selfie_verified_at = models.DateTimeField(null=True, blank=True)
    completed_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "demande d'enrôlement"
        verbose_name_plural = "demandes d'enrôlement"
        ordering = ["created_at"]
        indexes = [
            models.Index(fields=["status", "created_at"]),
            models.Index(fields=["phone", "created_at"]),
            models.Index(fields=["device_id", "created_at"]),
        ]
        permissions = [
            ("review_enrolment", "Peut approuver, refuser ou mettre en attente une demande"),
            ("send_enrolment_code", "Peut envoyer le numéro de confirmation"),
        ]

    def __str__(self):
        return f"{self.phone} ({self.get_status_display()})"


class RefreshToken(models.Model):
    device = models.ForeignKey(Device, on_delete=models.CASCADE, related_name="refresh_tokens")
    token_hash = models.CharField(max_length=64, unique=True)
    expires_at = models.DateTimeField()
    rotated_at = models.DateTimeField(null=True, blank=True)
    revoked_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)


